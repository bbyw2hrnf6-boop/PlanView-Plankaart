import {onRequest} from 'firebase-functions/v2/https';
import {defineSecret,defineString} from 'firebase-functions/params';
import {initializeApp} from 'firebase-admin/app';
import {getAuth} from 'firebase-admin/auth';
import {getFirestore} from 'firebase-admin/firestore';
import {readFileSync} from 'node:fs';
import {handleApi} from './generated/lib/ai.mjs';
import {firestoreDB} from './firestore-db.mjs';
import {allowedOrigins,createGateway} from './gateway.mjs';
import {createMonitoredEngine} from './monitored-engine.mjs';
import {createMonitorStore} from './monitor-store.mjs';
import {createWeeklyQuotaStore} from './weekly-quota.mjs';
import {createFeedbackStore} from './feedback-store.mjs';
import {createFeedbackApi} from './feedback-api.mjs';
import {createSearchFeedbackStore} from './search-feedback-store.mjs';
import {createSearchFeedbackApi} from './search-feedback-api.mjs';
initializeApp();
const credentialKey=defineSecret('PLANVIEW_CREDENTIAL_KEY');
const emails=defineString('PLANVIEW_ALLOWED_EMAILS',{default:'hirsch.danny@gmx.de'});
const testUserUid=defineString('PLANVIEW_TEST_USER_UID',{default:''});
const credentialOwnerUid=defineString('PLANVIEW_CREDENTIAL_OWNER_UID',{default:''});
const extraOrigins=defineString('PLANVIEW_EXTRA_ORIGINS',{default:''});
const config=JSON.parse(readFileSync(new URL('./generated/search_config.json',import.meta.url)));
const schema=JSON.parse(readFileSync(new URL('./generated/search_filters.schema.json',import.meta.url)));
const storage=firestoreDB(getFirestore());
const monitoring=createMonitorStore(getFirestore());
const weeklyQuota=createWeeklyQuotaStore(getFirestore());
const feedbackApi=createFeedbackApi({store:createFeedbackStore(getFirestore()),ownerUid:()=>credentialOwnerUid.value(),testUserUid:()=>testUserUid.value()});
const searchFeedbackApi=createSearchFeedbackApi({store:createSearchFeedbackStore(getFirestore()),ownerUid:()=>credentialOwnerUid.value(),testUserUid:()=>testUserUid.value()});
const monitoredEngine=createMonitoredEngine({engine:handleApi,store:monitoring,quotaStore:weeklyQuota,feedbackApi,searchFeedbackApi,ownerUid:()=>credentialOwnerUid.value(),testUserUid:()=>testUserUid.value(),
  onWriteError:()=>console.error('planview_monitor_write_failed'),onQuotaError:()=>console.error('planview_weekly_quota_failed')});
export const planviewApi=onRequest({region:'europe-west1',secrets:[credentialKey],timeoutSeconds:300,memory:'512MiB',minInstances:0,maxInstances:3,concurrency:10,serviceAccount:'planview-runtime@planview-ecf9b.iam.gserviceaccount.com',invoker:'public',cors:false},async(req,res)=>{
  const gateway=createGateway({verifyToken:token=>getAuth().verifyIdToken(token,true),allowedEmails:()=>emails.value(),testUserUid:()=>testUserUid.value(),origins:allowedOrigins(process.env.GCLOUD_PROJECT||JSON.parse(process.env.FIREBASE_CONFIG||'{}').projectId,extraOrigins.value()),engine:monitoredEngine,environment:()=>({DB:storage,PLANVIEW_CREDENTIAL_KEY:credentialKey.value(),PLANVIEW_CREDENTIAL_OWNER_UID:credentialOwnerUid.value()}),config,schema});
  return gateway(req,res);
});
